import React from "react";
import {
  AbsoluteFill,
  interpolate,
  useCurrentFrame,
  useVideoConfig,
} from "remotion";
import { fadeUp } from "../../components/animate";
import { Backdrop } from "../../components/Backdrop";
import { LayerStack } from "../../components/LayerStack";
import { PhoneMock } from "../../components/PhoneMock";
import { PhoneScreen } from "./PhoneScreen";
import { fonts } from "../../fonts";
import { colors, layerColors, sec, spacing } from "../../theme";

// Scene 4: The proof (0:37 to 0:50). See docs/video1-script.md.
// A device stands in for the viewer's own screen. The stack builds line by
// line on the spoken beats: software (animations are code), AI (generated the
// code), hardware (it plays on your device). Provisional timing.
const STACK_AT = sec(1);
const STACK_STAGGER = sec(3);
const HARDWARE_AT = STACK_AT + STACK_STAGGER * 2;
const FINAL_AT = sec(10);

export const Scene4Proof: React.FC = () => {
  const frame = useCurrentFrame();
  const { fps } = useVideoConfig();

  const glow = interpolate(frame, [HARDWARE_AT, HARDWARE_AT + 24], [0, 1], {
    extrapolateLeft: "clamp",
    extrapolateRight: "clamp",
  });
  const final = fadeUp(frame, fps, FINAL_AT);

  return (
    <Backdrop>
      <AbsoluteFill
        style={{
          flexDirection: "row",
          alignItems: "center",
          justifyContent: "center",
          gap: spacing.safe,
          paddingBottom: 120,
        }}
      >
        <PhoneMock
          delay={0}
          width={400}
          glow={glow}
          glowColor={layerColors.hardware}
        >
          <PhoneScreen
            softwareAt={STACK_AT}
            aiAt={STACK_AT + STACK_STAGGER}
            hardwareAt={HARDWARE_AT}
          />
        </PhoneMock>
        <LayerStack
          order={["software", "ai", "hardware"]}
          labels={{
            software: "Animations are code",
            ai: "Code generated by AI",
            hardware: "Playing on your device",
          }}
          width={880}
          delay={STACK_AT}
          stagger={STACK_STAGGER}
        />
      </AbsoluteFill>
      <AbsoluteFill
        style={{
          justifyContent: "flex-end",
          alignItems: "center",
          paddingBottom: 200,
        }}
      >
        <div
          style={{
            fontFamily: fonts.heading,
            fontWeight: 700,
            fontSize: 64,
            color: colors.white,
            opacity: final.opacity,
            translate: `0 ${final.translateY}px`,
          }}
        >
          Three layers, one video.{" "}
          <span style={{ color: colors.engineering }}>
            That&apos;s engineering.
          </span>
        </div>
      </AbsoluteFill>
    </Backdrop>
  );
};
